// theme-check.mjs — fail the build when the app has NO visual identity of its own.
//
// CANONICAL COPY. engine/emit-live-themes.mjs installs this into every app it touches
// (<app>/scripts/theme-check.mjs + a `prebuild` hook), because the apps that actually lose their
// theme are @kissflow/create-app scaffolds, which have their own package.json and never saw the
// starter's. starter/scripts/theme-check.mjs is a copy of this file — edit here.
//
//   node scripts/theme-check.mjs [appDir]        # defaults to cwd
//   node scripts/theme-check.mjs . --warn-only   # report, exit 0
//
// WHY THIS EXISTS. PromoTrack shipped a beautiful blue prototype and a monochrome custom UI. Nothing
// was broken: the app simply kept `src/app-theme.css` exactly as the scaffold ships it, because the
// generation step that replaces it is a line of prose in CONDUCTOR.md that an agent can skip. Three
// things made that failure invisible:
//
//   1. `DEFAULT_THEME = ""` is deliberate (see src/themes.js) — no anchor is forced, so a skipped
//      step leaves NO fallback identity at all, rather than a wrong one.
//   2. The shipped placeholder is valid, clean-looking CSS that "deliberately paints nothing
//      distinctive" — so the result reads as an intentional minimal design, not an error.
//   3. Nothing checked. The gate, the verifier and ui-lint are all silent on it.
//
// A silent wrong answer that looks deliberate is the worst failure mode this pipeline has, so this
// runs on `prebuild` alongside lint:ui and turns it into a loud one.
//
// ONE CANONICAL MECHANISM (settled 2026-08-04). An app's identity comes from the design slice its
// prototype was rendered with, and from nothing else:
//   engine/theme-from-design.mjs <runDir>/prototype/experience-spec.json --out src/app-identity.css
//
// That command also sets `<html data-theme>` to the app's DESIGN LANGUAGE — one of the blocks in
// src/tokens.css, which supplies the rest of the token contract. That is a different meaning from
// the anchor stamp this gate rejects — see the note at `language` below.
//
// A catalog anchor stamped via DEFAULT_THEME / <html data-theme> is NOT accepted as a substitute.
// It is a preset, not this app's design: it drops whatever kf-design-director varied for this app
// (hue shift, density, shell archetype), so the live app can still differ from the prototype that
// was reviewed — just less obviously than PromoTrack did. `emit-live-themes --default`/`--for` are
// retired and now exit with an error; that command emits infrastructure only (anchor catalog for
// the switcher, the Tailwind @theme bridge, themes.js, agents/theming.md) and sets no identity.

import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : ".";
const warnOnly = process.argv.includes("--warn-only");
const read = (p) => { try { return readFileSync(join(dir, p), "utf8"); } catch { return ""; } };

// A — the app's own design language, emitted from the SAME slice the prototype was rendered with.
// Positive detection on the generator's own banner: robust to someone editing the placeholder text,
// and it cannot be satisfied by a hand-written stub that never saw the design slice.
// src/app-identity.css is where the generator writes NOW; src/app-theme.css is where it used to,
// and both are checked. Reading only the new path would report "no identity" for every app built
// before the move, and reading only the old one would go green-on-nothing for every app built
// after it — a gate that silently stops gating is worse than no gate.
//
// Deliberately NOT checked here: the "TRANSCRIBED from Claude Design" banner in src/tokens.css.
// Every app scaffolded FROM the starter inherits that same tokens.css, so accepting the banner
// would pass every generated app for free — the exact green-on-nothing this gate exists to
// prevent. A generated app has to show the generator's own banner. The legitimately-empty case is
// handled by the explicit marker below instead, which a scaffold cannot satisfy by accident.
const appIdentity = read("src/app-identity.css");
const appTheme = read("src/app-theme.css");
const GENERATED = "GENERATED by engine/theme-from-design.mjs";
const hasOwnLanguage = appIdentity.includes(GENERATED) || appTheme.includes(GENERATED);

// ── THE ONE LEGITIMATELY-EMPTY CASE, DECLARED RATHER THAN INFERRED ───────────────────────────────
// Two apps genuinely have no accent of their own to declare, and both say so in this exact string:
//
//   · THIS starter — hand-transcribed against Beacon with per-token provenance. Adding an accent
//     would override the transcription the file exists to demonstrate.
//   · A generated app whose design slice names an anchor that IS its language. identityTokens()
//     returns nothing there, because the language already declares --primary, --brand-accent, the
//     accent pair, --ring, the chart ramp and --radius; re-emitting them could only repeat those
//     values or drift from them, and it drifted.
//
// CHECKED BEFORE hasOwnLanguage, DELIBERATELY. The previous version of this gate had the same
// marker but evaluated it inside the `hasOwnLanguage` branch — which the starter can never enter,
// because it carries no generator banner. So the one case the exemption was written for could not
// reach it, and this repo's own scaffold failed its own gate while carrying the marker that was
// supposed to excuse it. An exemption that the case it names cannot reach is not an exemption.
//
// This does not open the green-on-nothing hole the banner check closes: nothing hand-writes this
// string into a generated app, theme-from-design.mjs overwrites app-identity.css wholesale on every
// run, and it only emits the marker when the identity is empty BY CONSTRUCTION. A stale marker
// cannot survive a regeneration.
const IDENTITY_OPT_OUT = "IDENTITY: language-default";
if (appIdentity.includes(IDENTITY_OPT_OUT)) {
  console.log(`✓ theme-check: this app wears its design language unmodified — declared, not defaulted.
  src/app-identity.css carries "${IDENTITY_OPT_OUT}", so it has no accent of its own by intent.
  Remove that marker if the app should have one, then re-run theme-from-design.mjs.`);
  process.exit(0);
}

// B — a deliberately chosen preset from the 21-ANCHOR catalog.
//
// The banner check is load-bearing, not decoration. `create-app` scaffolds ship their own legacy
// registry of 7 ACCENT-ONLY presets (violet · blue · emerald · rose · amber · orange · neutral) that
// re-tint `primary` + `chart-1..5` and nothing else — no fonts, radius, shadows, spacing or type
// scale. An app left on those has a non-empty DEFAULT_THEME and a `data-theme` on <html>, so a check
// that only asked "is something set?" would pass it — and that is EXACTLY the state PromoTrack
// shipped in (`data-theme="violet"`, which is why the live app was monochrome with one purple
// accent while its prototype was blue). Requiring the generator's banner distinguishes an app that
// was upgraded to the real anchors from one that merely still has the scaffold's defaults.
const themesJs = read("src/themes.js");
const upgradedToAnchors = themesJs.includes("GENERATED by engine/emit-live-themes.mjs");
const defaultTheme = (/export const DEFAULT_THEME\s*=\s*(["'])(.*?)\1/.exec(themesJs) || [])[2] ?? null;
const html = read("index.html");
const dataTheme = (/<html[^>]*\bdata-theme\s*=\s*(["'])(.*?)\1/.exec(html) || [])[2] ?? null;
// `<html data-theme>` now carries TWO different meanings and they must not be confused. Its old
// meaning is the one this gate was built to catch: a catalog anchor (or a legacy accent preset)
// stamped in place of a real design. Its new meaning is which design LANGUAGE in src/tokens.css
// the app adopts, which is required, not a smell. Reading them as the same thing would fail every
// correctly-built app.
//
// THE LIST IS READ FROM THE APP'S OWN CONTRACT, not hardcoded here. This file is COPIED verbatim
// into every generated app as `scripts/theme-check.mjs` (emit-live-themes.mjs installs it), so it
// cannot import the plugin's catalog — and a hardcoded list is exactly how it went stale: it still
// said `beacon | nimbus | checkpoint` after the language set grew to eleven, which made an app
// correctly stamped `data-theme="iris"` report "no data-theme — the app falls back to BEACON" and,
// in the branch below, get accused of being themed by a catalog anchor. Asking the app's own
// tokens.css which languages it can actually serve is also the RIGHT question: a data-theme naming
// a block that file does not contain really does render as Beacon, whatever the catalog says.
const tokensCss = read("src/tokens.css");
const LANGUAGES = tokensCss
  // `\s*\{` is required: tokens.css's own prose writes `:root[data-theme="…"]` when explaining the
  // mechanism, and a match without the brace reads that comment as a language named "…".
  ? ["beacon", ...[...tokensCss.matchAll(/:root\[data-theme=(["'])([a-z][a-z0-9-]*)\1\]\s*\{/g)].map((m) => m[2])]
  // No tokens.css to ask (a bare scaffold, or this script run outside an app): fall back to the
  // one language that is always true — Beacon is `:root`, so it needs no block and no attribute.
  : ["beacon"];
const language = LANGUAGES.includes(dataTheme) ? dataTheme : null;
const stamped = language ? null : dataTheme;
const anchorOnly = upgradedToAnchors && Boolean(defaultTheme || stamped);

// ONE canonical source of identity: the design slice the prototype was rendered with. An anchor
// stamped via DEFAULT_THEME / <html data-theme> is NOT accepted as a substitute — it is a catalog
// preset, not this app's design, and it drops any per-app variation the design-director applied
// (hue shift, density, shell archetype) that the prototype is actually showing.
if (hasOwnLanguage) {
  const where = appIdentity.includes(GENERATED) ? "src/app-identity.css" : "src/app-theme.css (legacy path)";
  const notes = [];
  if (anchorOnly) notes.push(`an anchor is also stamped ("${defaultTheme || stamped}") — the identity sheet loads last and wins, but the anchor is redundant.`);
  // No language selected means the app renders as BEACON whatever its prototype was designed as,
  // and it does so silently: the identity sheet still applies the accent, so the app looks themed.
  if (!language) notes.push("no <html data-theme> — the app falls back to BEACON. Re-run theme-from-design.mjs so it can set the attribute, or add it by hand.");
  console.log(`✓ theme-check: app has its own design language (${where})`
    + (language ? `\n  language: ${language}` : "")
    + notes.map((n) => `\n  note: ${n}`).join(""));
  process.exit(0);
}

// Name the legacy case explicitly — "no identity" is confusing when the app visibly has a colour.
const onLegacyPresets = !upgradedToAnchors && Boolean(defaultTheme || stamped);
const headline = onLegacyPresets
  ? "this app is still on the scaffold's LEGACY accent-only presets — it never got its design."
  : anchorOnly
    ? `this app is themed by a catalog ANCHOR ("${defaultTheme || stamped}"), not by its own design.`
    : "this app has NO visual identity — it will render as the neutral scaffold.";

const msg = `
✗ theme-check: ${headline}

  src/app-identity.css ${appIdentity ? (appIdentity.includes(GENERATED) ? "generated" : "present, but still the shipped placeholder") : "missing"}
  src/app-theme.css    ${appTheme ? (appTheme.includes(GENERATED) ? "generated (legacy path)" : "present — the --kf-* alias layer") : "missing"}
  src/themes.js        ${upgradedToAnchors ? "anchor catalog present (switcher + bridge)" : "legacy 7 accent-only presets (not upgraded)"}
  DEFAULT_THEME        ${defaultTheme === null ? "not found" : defaultTheme === "" ? '"" (none — correct)' : `"${defaultTheme}"`}
  <html data-theme>    ${dataTheme === null ? "not set" : dataTheme === "" ? '"" (none — correct)' : `"${dataTheme}"${language ? " (design language — correct)" : " (an anchor/legacy preset, not a language)"}`}
${onLegacyPresets ? `
  The legacy presets re-tint 'primary' and 'chart-1..5' and NOTHING else — no fonts, radius,
  shadows, spacing or type scale. That is why such an app reads as monochrome with a single
  stray accent colour while its prototype is fully designed.
` : anchorOnly ? `
  A catalog anchor is not this app's design. It drops whatever the design-director varied for
  this app — hue shift, density, shell archetype — so the live app can still differ from the
  prototype that was reviewed, just less obviously.
` : ""}
  An app's identity has ONE source: the design slice its prototype was rendered with.

      node <plugin>/engine/theme-from-design.mjs \\
        <runDir>/prototype/experience-spec.json --out src/app-identity.css

  That writes the app's accent, focus, chart ramp and corner, AND sets <html data-theme> to the
  design language the slice adopts — ${LANGUAGES.join(" · ")} — which is what supplies the
  other ~130 tokens in src/tokens.css. Make sure main.jsx imports it LAST:
      import "./app-identity.css";

  Do NOT aim --out at src/app-theme.css: that file is the legacy --kf-* alias layer that
  kf-ui.css reads, and a full-file write deletes it. The generator now refuses.
${upgradedToAnchors ? "" : `
  This app also still has the legacy preset registry. Refresh the infrastructure first — the
  anchor catalog the theme switcher needs, and the @theme bridge that makes Tailwind utility
  classes theme-aware (it sets no default; identity stays the identity sheet's job):
      node <plugin>/engine/emit-live-themes.mjs --app .
`}`;

if (warnOnly) { console.warn(msg); process.exit(0); }
console.error(msg);
process.exit(1);
