// sync-tokens.mjs — copy the LIVE token contract from the starter kit into proto-kit.
//
// WHY THIS EXISTS. proto-kit and starter kit must render identically (the user's requirement:
// "the same components, the same UI, the same themes… whatever I saw in the prototype should get
// developed in custom UI generation"). The only honest way to guarantee that is ONE token contract,
// not two that are periodically eyeballed against each other. starter/src/tokens.css is that
// contract — ~200 tokens, a `@theme inline` bridge and 25 `@utility` classes, carrying the three
// design languages (Beacon as `:root`, plus ten `[data-theme]` blocks).
//
// WHY A COPY AND NOT AN IMPORT. The plugin ships standalone (.claude-plugin/marketplace.json:
// `"source": "./plugins/app-agents"`) and contains no copy of starter/. At an installed site
// `starter/src/tokens.css` does not exist, so the contract has to travel INSIDE the plugin. This
// script is what keeps the travelling copy honest — same pattern as emit-live-themes.mjs's
// "one generator, one source, one set of bugs".
//
//   node sync-tokens.mjs                 # sync + report drift
//   node sync-tokens.mjs --check         # exit 1 if out of date, write nothing (for CI)
//
// The emitted file is tokens.css in this directory. DO NOT EDIT IT BY HAND — edit
// starter/src/tokens.css and re-run this.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "tokens.css");

// The starter lives at the REPO ROOT, four levels up from plugins/app-agents/engine/proto-kit/.
// Overridable so the script still works from a checkout with a different layout.
const SRC = process.env.KF_STARTER_TOKENS
  || resolve(HERE, "..", "..", "..", "..", "starter", "src", "tokens.css");

// ── proto-kit's own bridge additions ─────────────────────────────────────────────────────────────
// VERIFIED GAP (2026-08-09): starter's `@theme inline` is NOT a superset of what proto-kit's recipes
// already use. These are the tokens the recipes reference that the contract does not export. Each is
// DERIVED from a contract token rather than invented, so a language switch still drives them and no
// new colour enters the system.
//
//   sidebar-foreground / -muted / -accent — 38 uses across COMPONENTS.md + the shell (the hero-band
//     `side-foot` template writes text-sidebar-muted; the nav CSS keys on .navitem.bg-sidebar-accent).
//     starter exports only --color-sidebar and --color-sidebar-border because its own sidebar is
//     painted by app-shell.jsx, which reaches for foreground/muted-foreground/primary directly.
//   success-foreground — starter exports --color-success but not its ink; proto-kit's badges and
//     Approve buttons need the pair.
//   chart1..8 (undashed) — proto-kit's markup predates the dashed names; aliased rather than
//     rewritten so existing recipes keep working.
const ADDITIONS = `
/* ─────────────────────────────────────────────────────────────────────────────────────────────────
 * proto-kit additions — GENERATED by sync-tokens.mjs, not part of starter's contract.
 *
 * Everything here is DERIVED from a token above, never a new colour: a language switch drives these
 * exactly as it drives the rest. They exist because proto-kit's recipes reference names starter's
 * own components do not (starter paints its sidebar in app-shell.jsx with foreground/primary
 * directly, so its bridge never needed to export the sidebar's ink).
 * ───────────────────────────────────────────────────────────────────────────────────────────────── */
@theme inline {
  /* The sidebar trio. --color-sidebar and --color-sidebar-border already come from the contract.
   * 2026-08-13: repointed from bare --foreground/--muted-foreground/--primary to their --color-*
   * equivalents. The bare layer these used to read doesn't exist post-Foundations migration
   * (tokens.css's own "NO MORE BARE-NAME LAYER" note) — these were only "working" when an app's own
   * identity block happened to ALSO define that bare name (theme-from-design.mjs's identityTokens()
   * still emits a few bare names for compat), which is exactly backwards: a base Beacon page with no
   * identity layered on top had these silently broken the whole time. --color-* is always defined,
   * app or no app, so this is the actually-robust fix, not a coincidental one. */
  --color-sidebar-foreground: var(--color-foreground);
  --color-sidebar-muted:      var(--color-muted-foreground);
  --color-sidebar-accent:     var(--color-primary);

  /* success needs its ink, like every other semantic pair in the contract. */
  --color-success-foreground: var(--color-primary-foreground);

  /* Undashed chart aliases — proto-kit markup says text-chart1, the contract says --color-chart-1. */
  --color-chart1: var(--chart-1);  --color-chart2: var(--chart-2);
  --color-chart3: var(--chart-3);  --color-chart4: var(--chart-4);
  --color-chart5: var(--chart-5);  --color-chart6: var(--chart-6);
  --color-chart7: var(--chart-7);  --color-chart8: var(--chart-8);

  /* The contract's radius ladder stops at xl; proto-kit's hero-band and pills need these two.
   * 2xl continues the same multiplier progression (lg ×1, xl ×1.3, 2xl ×1.6). */
  --radius-2xl: calc(var(--radius, 14px) * 1.6);
}

/* 2026-08-13 — the --tone-<name>-bg/-fg/-dot scheme, found DANGLING by audit: tokens.css's
 * Foundations rewrite names no --tone-* property at all (see its own banner) — every StatusChip/
 * Avatar/toast specimen across identity.mjs + behaviour.mjs reading one of these (~40 call sites)
 * was resolving to nothing, rendering unstyled. The real Chips.jsx moved away from --tone-*
 * entirely (now spells five tones × three roles as static Tailwind class literals — the only thing
 * that survives its JIT constraint on a dynamic 'tone' prop), but that fix doesn't transfer here:
 * the catalog reads these through inline style="background: var(--tone-x)", which has no such
 * constraint, so aliasing is both correct and far cheaper than rewriting ~40 call sites. No hsl()
 * wrapper needed — --color-*-bg/-ink are already full hsl() values.
 * pending/strong: Chips.jsx dropped both as STATUS tones ("orange and near-black are actions here,
 * not statuses") — no Foundations tone token to alias onto. Preserved at their old VISUAL colour
 * (primary orange / secondary near-black) rather than dropped, so an existing specimen keeps
 * rendering something coherent instead of going invisible again.
 *
 * 2026-08-13, later same day — moved out of @theme inline into a plain :root block AND changed
 * from var()-aliasing to literal hsl() values, on request (found DEAD, not just dangling — TWICE
 * over). First: the CDN JIT only emits an @theme inline custom property onto :root for names an
 * actual utility CLASS in the scanned markup references — --tone-success-bg etc. don't correspond
 * to any Tailwind namespace a class could ever be generated from, so this alias was never emitted
 * regardless of the ~40 var()-reading call sites it exists to serve. Moving the ALIAS to a plain
 * :root block alone does not fix that: verified live (PetroDesk) that --color-success-bg/-warning-
 * bg/-info-bg/-danger-bg — the tokens each alias points AT — are THEMSELVES only conditionally
 * emitted by the same JIT gate, for the exact same reason (they live in tokens.css's own @theme
 * inline block too). --color-success-ink read back fine only because something else on that one
 * page happened to use an unrelated class sharing it — proof this was never actually robust, just
 * accidentally working often enough not to be noticed. Literal values sidestep the gate entirely:
 * these five hsl() triples are copied verbatim from tokens.css's own --color-*-bg/-ink source
 * (this file's one designated place to duplicate a literal instead of aliasing, same as the
 * --gradient-* / --chart-* tokens above already do for the identical reason — keep that slash
 * spaced: an asterisk immediately followed by a slash closes this CSS comment early and
 * truncates the whole contract, found live 2026-08-13 breaking every prototype's styling). If
 * tokens.css's palette
 * is ever retuned, these six lines are the reminder to re-copy, not a second source of truth to
 * keep in sync automatically — there is no CSS mechanism that would do that safely here. */
:root {
  --tone-success-bg: hsl(150 41.2% 93.3%);  --tone-success-fg: hsl(152.3 82.5% 24.7%);  --tone-success-dot: hsl(150.8 82.6% 33.7%);
  --tone-warning-bg: hsl(40 88.2% 93.3%);   --tone-warning-fg: hsl(39.6 100% 27.1%);    --tone-warning-dot: hsl(42.7 94.8% 45.1%);
  --tone-info-bg: hsl(214.3 84% 95.1%);     --tone-info-fg: hsl(212.4 77.7% 35.1%);     --tone-info-dot: hsl(214.1 81.7% 50.6%);
  --tone-danger-bg: hsl(6 76.9% 94.9%);     --tone-danger-fg: hsl(3.9 72.5% 37.1%);     --tone-danger-dot: hsl(3.7 70.9% 49.8%);
  --tone-neutral-bg: hsl(240 12.5% 96.9%);  --tone-neutral-fg: hsl(240 4.8% 4.1%);      --tone-neutral-dot: hsl(220 1.2% 50.4%);
  --tone-pending-dot: hsl(22.6 100% 50.6%);    /* [preserved visual, not a status tone anymore] */
  --tone-strong-dot: hsl(240 4.8% 4.1%);       /* [preserved visual, not a status tone anymore] */
}
`;

const BANNER = (srcPath) => `/* ═══════════════════════════════════════════════════════════════════════════════════════════════
 * GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Source:      starter/src/tokens.css  (the live token contract the built app renders with)
 * Generator:   engine/proto-kit/sync-tokens.mjs
 * Regenerate:  node engine/proto-kit/sync-tokens.mjs
 *
 * proto-kit renders prototypes with the SAME contract the custom UI is built with, so a prototype
 * cannot show something the built app can't produce. Edit the source, not this copy.
 *
 * Consumed by a static page under the Tailwind v4 BROWSER CDN. The head it needs is written out in
 * gen-catalog.mjs; it is NOT reproduced here, because this file is embedded INSIDE that page's style
 * element and an HTML parser closes that element at the first closing-style tag it sees — inside a
 * CSS comment or not. Spelling the tag out here silently truncated the whole contract and every
 * component rendered unstyled (2026-08-09). gen-catalog.mjs now refuses to emit if one reappears.
 *
 * The two @import lines that head carries are load-bearing — verified in-browser: without them
 * NOTHING compiles (every @utility renders as a no-op, silently). They also keep preflight OFF,
 * which is what starter does (shadcn.css: "CRITICAL: preflight is OFF") and what this contract
 * assumes — border-decor sets border-style explicitly precisely because the UA default is 'none'.
 *
 * The v3 play CDN (cdn.tailwindcss.com) CANNOT run this file: @utility and @theme are v4 syntax and
 * are ignored without error there.
 * ═══════════════════════════════════════════════════════════════════════════════════════════════ */

`;

const build = () => {
  if (!existsSync(SRC)) {
    console.error(`sync-tokens: source not found — ${SRC}`);
    console.error("set KF_STARTER_TOKENS=<path to starter/src/tokens.css> if the layout differs.");
    process.exit(2);
  }
  return BANNER(SRC) + readFileSync(SRC, "utf8").replace(/\s*$/, "\n") + ADDITIONS;
};

const next = build();
const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;

if (process.argv.includes("--check")) {
  if (prev === next) { console.log("sync-tokens: up to date"); process.exit(0); }
  console.error("sync-tokens: OUT OF DATE — run `node engine/proto-kit/sync-tokens.mjs`");
  process.exit(1);
}

writeFileSync(OUT, next);
// Match a DECLARATION (`@utility name {`), not the words "@utility classes" in this file's own
// banner prose — which is what an unanchored /@utility\s+[\w-]+/ counted, reporting 28 for 25.
const utilities = (next.match(/^@utility\s+[\w-]+\s*\{/gm) || []).length;
const languages = (next.match(/:root\[data-theme="[^"]+"\]\s*\{/g) || []).length + 1; // +1 for :root
console.log(
  `tokens.css → ${OUT}\n` +
  `  ${next.split("\n").length} lines · ${utilities} @utility classes · ${languages} languages` +
  (prev === null ? " · created" : prev === next ? " · unchanged" : " · UPDATED")
);
