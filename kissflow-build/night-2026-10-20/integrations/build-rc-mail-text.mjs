// 27 Oct: builds scripts/rc-mail-text.js (request.changed · step "RC mail text") with the SAME e-mail layout as the
// screens (prototype/src/domain/emailHtml.ts, transpiled and inlined: a Kissflow script step can't import code).
//   node build-rc-mail-text.mjs   then set-code.mjs into the step
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { transformSync } from "../../../prototype/node_modules/esbuild/lib/main.js";
const here = (f) => fileURLToPath(new URL(f, import.meta.url));
const ts = readFileSync(here("../../../prototype/src/domain/emailHtml.ts"), "utf8");
const lib = transformSync(ts, { loader: "ts", format: "esm", target: "es2019" }).code.replace(/^export /gm, "");
const logic = `
// ---- the reviewers' mail (22 Oct; layout 27 Oct): the addresses from "Get user data" (the members of the case's
// department roles), one mail to all of them.
const emails = new Set();
const walk = (v) => { if (typeof v === "string") { try { const j = JSON.parse(v); if (j && typeof j === "object") walk(j); } catch (e) {} return; }
  if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) { if (/^email$/i.test(k) && typeof x === "string" && /^[^@\\s]+@[^@\\s]+$/.test(x.trim())) emails.add(x.trim().toLowerCase()); else walk(x); } };
walk(inputData.users);
if (!emails.size) throw new Error("NO MAIL (by design): the department roles have no members with an e-mail");
const code = String(inputData.caseCode || ""), trade = String(inputData.tradeName || ""), supplier = String(inputData.supplier || "The supplier");
const report = inputData.isReport === "yes";
const details = [{ label: "Case", value: code }, ...(trade ? [{ label: "Material", value: trade }] : []), { label: "Supplier", value: supplier }];
return {
  To: [...emails],
  Subject: report ? \`\${code}: the supplier reported a change\` : \`\${code}: the supplier changed the CIQ\`,
  Body: emailHtml({
    title: report ? "The supplier reported a change" : "The supplier changed the CIQ",
    intro: report ? \`\${supplier} reported a change on the released CIQ of \${code}.\` : \`\${supplier} changed the CIQ of \${code} after confirming its completeness.\`,
    details,
    ...(report && inputData.reportText ? { quotes: [{ label: "Change report", text: String(inputData.reportText) }] } : {}),
    notes: ["Please open CIQ Digital to see the change."],
  }),
};
`;
writeFileSync(here("scripts/rc-mail-text.js"), `// request.changed · step "RC mail text" (GENERATED by build-rc-mail-text.mjs from prototype/src/domain/emailHtml.ts; do not edit by hand)\n${lib}\n${logic}`);
console.log("written", (lib.length + logic.length), "chars");
